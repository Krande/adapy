"""Generate the frontend's weld symbols from ``ada.api.weld_symbols``.

The symbols are defined once, in Python (``ada.api.weld_symbols``). The viewer draws them without
asking the server: this script writes their geometry into a TypeScript module, and
``src/frontend/src/utils/weldSymbols.ts`` renders it to the same SVG as
:meth:`ada.api.weld_symbols.WeldSymbol.to_svg`. Two files are written:

* ``src/frontend/src/utils/weldSymbols.generated.ts``: each symbol's description, strokes, outlines
  and fills, keyed by the ``WeldType`` value, every path a flat ``[x0, y0, x1, y1, ...]`` list;
* ``src/frontend/src/__tests__/fixtures/weld_symbols/expected_svgs.json``: Python's ``to_svg`` of
  every symbol (and a few with other options), which the frontend test asserts its renderer
  reproduces character for character.

Coordinates are rounded to ``DECIMALS`` places to keep the module small; the script refuses to
write a module whose rounded geometry would draw a different SVG than the exact one.

Run it from anywhere (``python scripts/codegen/gen_weld_symbols.py``); ``--check`` fails instead of
writing when the committed files are stale, and ``tests/core/test_weld_symbols_codegen.py`` does
the same in the test suite.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

# Relative to the repo root.
MODULE_PATH = pathlib.Path("src/frontend/src/utils/weldSymbols.generated.ts")
FIXTURE_PATH = pathlib.Path("src/frontend/src/__tests__/fixtures/weld_symbols/expected_svgs.json")
DECIMALS = 6

#: Options besides the defaults (Python's keyword names), each with the weld types the fixture draws it
#: for (None: every one; the rounding check draws every symbol with every variant). Drawing both sides moves the
#: geometry and the view, so every symbol is drawn so; the rest change the same few attributes of any symbol.
VARIANTS: tuple[tuple[dict, tuple[str, ...] | None], ...] = (
    ({"side": "other"}, ("FILLET", "SPOT", "BEVEL_BACKING", "J_GROOVE_J_BUTT")),
    ({"side": "both"}, None),
    ({"size": 18}, ("FILLET",)),
    ({"size": 48, "stroke": "#ff8800", "stroke_width": 0.1}, ("FILLET", "SPOT", "MELT_THROUGH")),
    ({"size": 32, "reference_line": False}, ("FILLET", "SPOT", "MELT_THROUGH")),
    ({"size": 32, "reference_line": False, "side": "both"}, ("FILLET", "SEAM")),
)


def _num(v: float) -> str:
    return repr(round(v, DECIMALS) + 0.0).removesuffix(".0")  # + 0.0: no "-0"


def _flat(path) -> str:
    return "[" + ",".join(f"{_num(x)},{_num(y)}" for x, y in path) + "]"


def _rounded(symbol):
    from ada.api.weld_symbols import WeldSymbol

    def r(paths):
        return tuple(tuple((round(x, DECIMALS) + 0.0, round(y, DECIMALS) + 0.0) for x, y in p) for p in paths)

    return WeldSymbol(symbol.weld_type, symbol.description, r(symbol.strokes), r(symbol.outlines), r(symbol.fills))


def _symbols():
    from ada.api.fasteners import WeldType
    from ada.api.weld_symbols import weld_symbol

    return [s for s in (weld_symbol(wt) for wt in WeldType if wt is not WeldType.NONE) if s is not None]


def build_module() -> str:
    symbols = _symbols()
    # The rounding must not show: the rounded geometry draws exactly what the exact one does.
    for s in symbols:
        for opts in ({}, *(v for v, _ in VARIANTS)):
            if _rounded(s).to_svg(**opts) != s.to_svg(**opts):
                raise SystemExit(f"{s.weld_type.value}: rounding to {DECIMALS} places changes its SVG; raise DECIMALS")

    lines = [
        "// Generated by scripts/codegen/gen_weld_symbols.py from ada.api.weld_symbols -- do not hand-edit.",
        "// Each weld type's ISO 2553 basic symbol as geometry on the reference line (y = 0) in the unit box,",
        "// y up; every path a flat [x0, y0, x1, y1, ...] list. Rendered by ./weldSymbols.ts.",
        "",
        "export interface WeldSymbolGeometry {",
        "  /** What the symbol stands for, as ISO 2553 names it. */",
        "  readonly description: string;",
        "  /** Open polylines. */",
        "  readonly strokes: readonly (readonly number[])[];",
        "  /** Closed outlines, drawn, not filled. */",
        "  readonly outlines: readonly (readonly number[])[];",
        "  /** Filled polygons. */",
        "  readonly fills: readonly (readonly number[])[];",
        "  /** Centred on the reference line (spot, seam): the same on either side. */",
        "  readonly centred?: true;",
        "}",
        "",
        "/** Keyed by the `ada.api.fasteners.WeldType` value; `NONE` has no symbol. */",
        "export const WELD_SYMBOLS: Readonly<Record<string, WeldSymbolGeometry>> = {",
    ]
    for s in symbols:
        parts = [f"description: {json.dumps(s.description)}"]
        for name, paths in (("strokes", s.strokes), ("outlines", s.outlines), ("fills", s.fills)):
            parts.append(f"{name}: [{', '.join(_flat(p) for p in paths)}]")
        if s.centred:
            parts.append("centred: true")
        lines.append(f"  {s.weld_type.value}: {{ {', '.join(parts)} }},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def build_fixture() -> str:
    symbols = _symbols()
    payload = {
        "comment": "Generated by scripts/codegen/gen_weld_symbols.py -- do not hand-edit. "
        "Python's WeldSymbol.to_svg per weld type, with its default options and with each variant's.",
        "default": {s.weld_type.value: s.to_svg() for s in symbols},
        "variants": [
            {
                "options": v,
                "svgs": {
                    s.weld_type.value: s.to_svg(**v) for s in symbols if types is None or s.weld_type.value in types
                },
            }
            for v, types in VARIANTS
        ],
    }
    return json.dumps(payload, indent=1) + "\n"


def is_current(path: pathlib.Path, text: str) -> bool:
    """Whether ``path`` holds ``text``; a checkout's CRLF line ends are the same text."""
    return path.exists() and path.read_bytes().replace(b"\r\n", b"\n") == text.encode("utf-8")


def outputs(root: pathlib.Path) -> dict[pathlib.Path, str]:
    return {root / MODULE_PATH: build_module(), root / FIXTURE_PATH: build_fixture()}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--root",
        type=pathlib.Path,
        default=pathlib.Path(__file__).resolve().parents[2],
        help="repository root (default: the checkout this script lives in)",
    )
    ap.add_argument("--check", action="store_true", help="fail instead of writing when stale")
    args = ap.parse_args(argv)

    # The symbols of this checkout, whichever ada the environment has installed.
    sys.path.insert(0, str(args.root / "src"))
    files = outputs(args.root)
    if args.check:
        stale = [str(p) for p, text in files.items() if not is_current(p, text)]
        if stale:
            print("stale (run scripts/codegen/gen_weld_symbols.py):\n  " + "\n  ".join(stale), file=sys.stderr)
            return 1
        print("weld symbols are current")
        return 0
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
