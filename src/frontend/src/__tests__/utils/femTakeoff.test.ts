import assert from "node:assert/strict";
import { test } from "node:test";

import type { EquipmentGlyph, LoadScenario } from "@/extensions/design_and_analysis_extension";
import { useFemConceptsStore } from "@/state/femConceptsStore";
import {
  defaultEquipmentGroups,
  equipmentCog,
  equipmentGroupLabel,
  equipmentGroups,
  femTakeoff,
  scenarioResultant,
  visibleEquipment,
  visibleLoads,
} from "@/utils/fem/femTakeoff";

// The Scene > FEM take-off weighs what the panel switches on. The rule that matters most: an
// analysis model's wind "equipment" is a heavy box placed only to generate a wind load, and must
// not be weighed unless asked for -- so equipment starts switched on only in groups placed in a
// load case that carries an acceleration.

const I: EquipmentGlyph["axes"] = [
  [1, 0, 0],
  [0, 1, 0],
  [0, 0, 1],
];

const eq = (name: string, mass: number, loadCases: string[], cog: [number, number, number]): EquipmentGlyph => ({
  name,
  mass,
  origin: [cog[0], cog[1], 0],
  axes: I,
  box_min: [-1, -1, 0],
  box_max: [1, 1, 2 * cog[2]],
  cog,
  load_cases: loadCases,
});

const GRAVITY_CASES = ["Selfweight", "Acc_x"];
const deck = eq("trafo", 20_000, GRAVITY_CASES, [10, 0, 1]);
const pump = eq("pump", 5_000, ["Acc_x", "Selfweight"], [0, 10, 1]);
const wind = eq("Wind_PosY_eq1", 600_000, ["Wind_PosY"], [0, 0, 5]);

const scenarios: LoadScenario[] = [
  { name: "Selfweight", kind: "case", loads: [{ type: "accel", direction: [0, 0, -1], magnitude: 9.81 }] },
  { name: "Acc_x", kind: "case", loads: [{ type: "accel", direction: [1, 0, 0], magnitude: 1 }] },
  { name: "Wind_PosY", kind: "case", loads: [] },
];

test("equipment groups by the load cases placing it, whatever order they are listed in", () => {
  const groups = equipmentGroups([deck, pump, wind]);
  assert.equal(groups.length, 2);
  const gravity = groups.find((g) => g.items.includes(deck))!;
  assert.deepEqual(gravity.items, [deck, pump]);
  assert.equal(gravity.mass, 25_000);
  assert.equal(equipmentGroupLabel(gravity), "Acc_x +1");
});

test("only groups placed in an accelerated case start switched on", () => {
  const groups = equipmentGroups([deck, pump, wind]);
  const on = defaultEquipmentGroups(groups, scenarios);
  const visible = visibleEquipment([deck, pump, wind], true, on);
  assert.deepEqual(visible, [deck, pump], "the wind area is a load generator, not weight");
  assert.deepEqual(visibleEquipment([deck, pump, wind], false, on), [], "the master switch hides every group");
});

test("the take-off sums what is switched on, with a mass-weighted centre of gravity", () => {
  const t = femTakeoff({
    model: { mass: 100, cog: [0, 0, 10], count: 7 },
    masses: [{ name: "m", position: [0, 0, 0], mass: 25_000 }],
    equipment: [deck, pump],
  });
  assert.deepEqual(
    t.rows.map((r) => [r.key, r.mass, r.count]),
    [
      ["model", 100, 7],
      ["masses", 25, 1],
      ["equipment", 25, 2],
    ],
  );
  assert.deepEqual(t.rows[2].cog, [8, 2, 1]);
  assert.equal(t.total, 150);
  // (100*[0,0,10] + 25*[0,0,0] + 25*[8,2,1]) / 150
  assert.deepEqual(
    t.cog!.map((v) => +v.toFixed(6)),
    [+(200 / 150).toFixed(6), +(50 / 150).toFixed(6), +(1025 / 150).toFixed(6)],
  );
});

test("switching everything off leaves nothing to weigh", () => {
  const t = femTakeoff({ model: null, masses: [], equipment: [] });
  assert.deepEqual(t.rows, []);
  assert.equal(t.total, 0);
  assert.equal(t.cog, null);
});

test("an item without a centre of gravity weighs at the centre of its turned box", () => {
  // Standing on its side: local z along -y, so the box's height runs towards -y.
  const sideways: EquipmentGlyph = {
    mass: 1,
    origin: [0, 0, 0],
    axes: [
      [1, 0, 0],
      [0, 0, 1],
      [0, -1, 0],
    ],
    box_min: [-2, -1, 0],
    box_max: [2, 1, 4],
  };
  assert.deepEqual(equipmentCog(sideways), [0, -2, 0]);
});

test("the resultant is point forces plus each line load's mean intensity times its length", () => {
  const loads: LoadScenario["loads"] = [
    { type: "point", position: [0, 0, 0], direction: [0, 0, -1], magnitude: 1000 },
    // 2 m rising from 100 to 300 N/m: 400 N
    { type: "line", position: [0, 0, 0], end_position: [2, 0, 0], direction: [0, 0, -1], magnitude: 100, end_magnitude: 300 },
    // generated by equipment: 1 m at 50 N/m along +y
    { type: "line", position: [0, 0, 0], end_position: [0, 0, 1], direction: [0, 1, 0], magnitude: 50, generated_by: "trafo" },
    { type: "accel", direction: [0, 0, -1], magnitude: 9.81 },
  ];
  const all = scenarioResultant(loads);
  assert.deepEqual(all.force, [0, 50, -1400]);
  assert.equal(all.accelerations, 1);

  const scenario: LoadScenario = { name: "LC", loads };
  assert.equal(visibleLoads(scenario, false).length, 3, "equipment loads switched off");
  assert.deepEqual(scenarioResultant(visibleLoads(scenario, false)).force, [0, 0, -1400]);
});

test("the store starts a new equipment group at its default and keeps the user's switch for an old one", () => {
  const store = useFemConceptsStore.getState();
  store.setData({ masses: [], bcs: [], scenarios, equipment: [deck, pump, wind] });
  const groups = equipmentGroups([deck, pump, wind]);
  const gravityKey = groups.find((g) => g.items.includes(deck))!.key;
  const windKey = groups.find((g) => g.items.includes(wind))!.key;
  assert.equal(useFemConceptsStore.getState().equipmentGroupOn[gravityKey], true);
  assert.equal(useFemConceptsStore.getState().equipmentGroupOn[windKey], false);

  store.setEquipmentGroupOn(windKey, true);
  store.setData({ masses: [], bcs: [], scenarios, equipment: [deck, pump, wind] });
  assert.equal(useFemConceptsStore.getState().equipmentGroupOn[windKey], true, "a reload keeps the user's switch");
});
