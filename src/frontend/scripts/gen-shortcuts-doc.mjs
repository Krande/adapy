#!/usr/bin/env node
// Generates docs/SHORTCUTS.md from src/shell/shortcuts.ts.
//
// The registry is the source; this is a rendering of it. Generating rather than writing
// the reference by hand is the point — a hand-written one is a second copy of the same
// facts, and it is the copy that goes stale, because nothing breaks when it does.
//
// Run: `npm run gen:shortcuts`. The output is committed so the reference is reviewable
// in a diff (and so the M0 shortcut capture can be compared against it).

import {readFileSync, writeFileSync, mkdirSync} from "node:fs";
import {dirname, resolve} from "node:path";
import {fileURLToPath} from "node:url";

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const REGISTRY = resolve(ROOT, "src/shell/shortcuts.ts");
export const DOC = resolve(ROOT, "docs/SHORTCUTS.md");

// Parse the object literals rather than importing the module: this script runs in plain
// node with no TS pipeline, and the registry is deliberately a flat list of literals so
// it can be read this way.
export function parseShortcuts(src) {
    return [...src.matchAll(/\{id:\s*"([^"]+)",\s*keys:\s*"([^"]+)",\s*label:\s*"([^"]+)",\s*scope:\s*"([^"]+)",\s*group:\s*"([^"]+)"\}/g)].map(
        (m) => ({id: m[1], keys: m[2], label: m[3], scope: m[4], group: m[5]}),
    );
}

const SCOPE_NOTE = {
    global: "Anywhere except a text input.",
    builder: "Only while a procedural model is open.",
    gallery: "Only in gallery mode.",
    shell: "Anywhere.",
};

/**
 * Render the reference. Exported so a test can regenerate and compare without writing
 * anything — a generated file that is committed but never checked is just a hand-written
 * file with extra steps, and this one had already drifted by a renamed label.
 */
export function renderShortcutsDoc(registrySrc) {
    const entries = parseShortcuts(registrySrc);
    if (entries.length === 0) throw new Error("no shortcuts parsed — has the registry's shape changed?");
const groups = [...new Set(entries.map((e) => e.group))];
const lines = [
    "# Keyboard shortcuts",
    "",
    "<!-- GENERATED by scripts/gen-shortcuts-doc.mjs from src/shell/shortcuts.ts.",
    "     Do not edit by hand — change the registry and re-run `npm run gen:shortcuts`. -->",
    "",
    "The registry that produces this file also feeds the command palette and every",
    "tooltip, so what you read here is what the app actually binds.",
    "`src/__tests__/shell/shortcuts.test.ts` checks the global entries against the real",
    "handler in both directions, so neither a broken promise nor an undocumented binding",
    "can survive CI.",
    "",
];

for (const g of groups) {
    lines.push(`## ${g}`, "");
    lines.push("| Keys | Action | Applies |", "|---|---|---|");
    for (const e of entries.filter((x) => x.group === g)) {
        lines.push(`| \`${e.keys}\` | ${e.label} | ${SCOPE_NOTE[e.scope] ?? e.scope} |`);
    }
    lines.push("");
}

    return {text: lines.join("\n"), entries, groups};
}

// Writing only when run as a script, so importing this for the test has no side effects.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const {text, entries, groups} = renderShortcutsDoc(readFileSync(REGISTRY, "utf8"));
    mkdirSync(dirname(DOC), {recursive: true});
    writeFileSync(DOC, text, "utf8");
    console.log(`wrote docs/SHORTCUTS.md — ${entries.length} shortcuts in ${groups.length} groups`);
}
